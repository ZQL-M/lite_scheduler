package com.tuba.schedulercore.enums;

/**
 * 调度器状态枚举
 */
public enum SchedulerStatus {
    
    /**
     * 已启动 - 调度器正在运行，可以执行任务调度
     * <p>
     * 状态说明：
     * - 调度器已初始化完成
     * - 正在监听和触发已注册的任务
     * - 可以接受新的任务注册和调度请求
     * </p>
     */
    STARTED,
    
    /**
     * 已暂停 - 调度器暂时停止任务调度，但可以随时恢复
     * <p>
     * 状态说明：
     * - 调度器仍在运行，但不会触发新的任务执行
     * - 已注册的任务保持不变
     * - 可以通过 resume() 方法恢复到 STARTED 状态
     * - 适用于临时停止所有任务执行的场景
     * </p>
     */
    PAUSED,
    
    /**
     * 已停止 - 调度器已完全停止，需要重新启动才能工作
     * <p>
     * 状态说明：
     * - 调度器已关闭，不再执行任何任务
     * - 所有资源已释放
     * - 需要调用 start() 方法才能重新开始工作
     * - 适用于系统关闭或重启的场景
     * </p>
     */
    STOPPED
}
